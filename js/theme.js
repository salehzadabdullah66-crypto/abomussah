class ThemeEngine {
  constructor() {
    this.currentTheme = localStorage.getItem('aya_theme') || 'dark';
    this.currentLang = localStorage.getItem('aya_lang') || 'ar';
    this.init();
  }

  init() {
    this.applyTheme(this.currentTheme);
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  applyTheme(theme) {
    this.currentTheme = theme;
    document.documentElement.setAttribute('data-theme', theme);
    localStorage.setItem('aya_theme', theme);

    const themeIcons = document.querySelectorAll('.theme-toggle-icon');
    themeIcons.forEach(icon => {
      icon.className = theme === 'dark' ? 'fas fa-sun theme-toggle-icon' : 'fas fa-moon theme-toggle-icon';
    });
  }

  playToggleSound(theme) {
    try {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      if (!AudioCtx) return;
      if (!this.audioCtx) {
        this.audioCtx = new AudioCtx();
      }
      if (this.audioCtx.state === 'suspended') {
        this.audioCtx.resume();
      }

      const osc = this.audioCtx.createOscillator();
      const gain = this.audioCtx.createGain();

      osc.type = 'sine';
      
      if (theme === 'light') {
        // Ascending tone for Light mode (Sun)
        osc.frequency.setValueAtTime(440, this.audioCtx.currentTime);
        osc.frequency.exponentialRampToValueAtTime(880, this.audioCtx.currentTime + 0.12);
      } else {
        // Descending tone for Dark mode (Moon)
        osc.frequency.setValueAtTime(750, this.audioCtx.currentTime);
        osc.frequency.exponentialRampToValueAtTime(380, this.audioCtx.currentTime + 0.12);
      }

      gain.gain.setValueAtTime(0.18, this.audioCtx.currentTime);
      gain.gain.exponentialRampToValueAtTime(0.001, this.audioCtx.currentTime + 0.12);

      osc.connect(gain);
      gain.connect(this.audioCtx.destination);

      osc.start();
      osc.stop(this.audioCtx.currentTime + 0.13);
    } catch (e) {
      console.warn('Audio playback error', e);
    }
  }

  toggleTheme() {
    const newTheme = this.currentTheme === 'dark' ? 'light' : 'dark';
    this.applyTheme(newTheme);
    this.playToggleSound(newTheme);
  }

  applyLanguage(lang) {
    this.currentLang = lang;
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    document.body.style.direction = lang === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem('aya_lang', lang);

    const dict = i18nDictionary[lang];
    if (dict) {
      // Update HTML title if current page title exists in dictionary
      const pageFile = window.location.pathname.split('/').pop().replace('.html', '') || 'index';
      if (dict[`page_title_${pageFile}`]) {
        document.title = dict[`page_title_${pageFile}`];
      }

      // Update elements with data-i18n attribute
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
          if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.setAttribute('placeholder', dict[key]);
            if (el.type === 'submit' || el.type === 'button') el.value = dict[key];
          } else if (el.tagName === 'OPTION') {
            el.textContent = dict[key];
          } else {
            // Check for child icon
            const icon = el.querySelector('i, svg');
            if (icon) {
              const iconHTML = icon.outerHTML;
              const hasPrefixIcon = el.firstElementChild === icon;
              if (hasPrefixIcon) {
                el.innerHTML = iconHTML + ' ' + dict[key];
              } else {
                el.innerHTML = dict[key] + ' ' + iconHTML;
              }
            } else {
              if (dict[key].includes('<br>') || dict[key].includes('<span>')) {
                el.innerHTML = dict[key];
              } else {
                el.textContent = dict[key];
              }
            }
          }
        }
      });

      // Update elements with data-i18n-placeholder
      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
          el.setAttribute('placeholder', dict[key]);
        }
      });
    }

    // Toggle button text (EN / AR)
    const langButtons = document.querySelectorAll('.lang-toggle-text');
    langButtons.forEach(btn => {
      btn.textContent = lang === 'ar' ? 'EN' : 'AR';
    });

    // Notify custom listeners if needed
    window.dispatchEvent(new CustomEvent('aya_language_changed', { detail: { lang } }));
  }

  toggleLanguage() {
    const newLang = this.currentLang === 'ar' ? 'en' : 'ar';
    this.applyLanguage(newLang);
  }

  bindEvents() {
    document.addEventListener('click', (e) => {
      if (e.target.closest('.theme-toggle-btn')) {
        this.toggleTheme();
      }
      if (e.target.closest('.lang-toggle')) {
        this.toggleLanguage();
      }
    });
  }
}

// Initialize Global Theme Instance
window.themeEngine = new ThemeEngine();

